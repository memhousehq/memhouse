  defp install_foreign_keys do
    Enum.each(@foreign_keys, fn {table_name, column, target, on_delete} ->
      execute """
      ALTER TABLE #{table_name}
      ADD CONSTRAINT #{table_name}_#{column}_fkey
      FOREIGN KEY (#{column}) REFERENCES #{target}(id) ON DELETE #{on_delete}
      """
    end)
  end

  defp remove_foreign_keys do
    Enum.each(Enum.reverse(@foreign_keys), fn {table_name, column, _target, _on_delete} ->
      execute "ALTER TABLE #{table_name} DROP CONSTRAINT IF EXISTS #{table_name}_#{column}_fkey"
    end)
  end


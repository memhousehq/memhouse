  defp install_rls do
    execute "ALTER TABLE accounts ENABLE ROW LEVEL SECURITY"
    execute "ALTER TABLE accounts FORCE ROW LEVEL SECURITY"

    execute """
    CREATE POLICY cartulary_account_wall ON accounts
    USING (
      id = NULLIF(current_setting('memhouse.account_id', true), '')::uuid
      OR key = NULLIF(current_setting('memhouse.account_key', true), '')
    )
    WITH CHECK (
      id = NULLIF(current_setting('memhouse.account_id', true), '')::uuid
      OR key = NULLIF(current_setting('memhouse.account_key', true), '')
    )
    """

    Enum.each(@account_tables, fn table_name ->
      execute "ALTER TABLE #{table_name} ENABLE ROW LEVEL SECURITY"
      execute "ALTER TABLE #{table_name} FORCE ROW LEVEL SECURITY"

      execute """
      CREATE POLICY cartulary_account_wall ON #{table_name}
      USING (
        account_id = NULLIF(current_setting('memhouse.account_id', true), '')::uuid
      )
      WITH CHECK (
        account_id = NULLIF(current_setting('memhouse.account_id', true), '')::uuid
      )
      """
    end)
  end

  defp remove_rls do
    Enum.each(Enum.reverse(@account_tables), fn table_name ->
      execute "DROP POLICY IF EXISTS cartulary_account_wall ON #{table_name}"
      execute "ALTER TABLE #{table_name} NO FORCE ROW LEVEL SECURITY"
      execute "ALTER TABLE #{table_name} DISABLE ROW LEVEL SECURITY"
    end)

    execute "DROP POLICY IF EXISTS cartulary_account_wall ON accounts"
    execute "ALTER TABLE accounts NO FORCE ROW LEVEL SECURITY"
    execute "ALTER TABLE accounts DISABLE ROW LEVEL SECURITY"
  end
